// Builds src/features/catalog/unreliable-prices.ts, the cards whose Cardmarket price on TCGdex belongs to another card.
// A Cardmarket product is one card. When TCGdex links one product to several cards of a set, only the card with the
// lowest number keeps the price, since it is the base print in every case checked by hand (for example the Mega
// Rayquaza ex of Delta Reign, whose special illustration showed the price of the plain card). The others show no price.
// Run it again from the mobile folder when prices look wrong, with: node scripts/build-unreliable-prices.mjs
// It reads every card of TCGdex, which takes about ten minutes.

import { writeFileSync } from 'node:fs';

const API = 'https://api.tcgdex.net/v2/en';
const CONCURRENCY = 8;

const pause = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

/** TCGdex sometimes fails for a moment, so each request gets several tries. */
async function get(path) {
  for (let attempt = 0; attempt < 6; attempt++) {
    const response = await fetch(`${API}${path}`).catch(() => undefined);
    if (response?.ok) return response.json();
    if (response?.status === 404) return undefined;
    await pause(1000 * (attempt + 1));
  }
  throw new Error(`No answer from ${API}${path}`);
}

async function inParallel(items, work) {
  const results = [];
  let next = 0;
  const worker = async () => {
    while (next < items.length) {
      const index = next++;
      results[index] = await work(items[index]);
    }
  };
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  return results;
}

const byNumber = (a, b) => a.localId.localeCompare(b.localId, 'en', { numeric: true });

const unreliable = {};
let total = 0;

for (const { id: setId } of await get('/sets')) {
  const set = await get(`/sets/${encodeURIComponent(setId)}`);
  const cards = await inParallel(set?.cards ?? [], (card) => get(`/cards/${encodeURIComponent(card.id)}`));
  const byProduct = new Map();
  for (const card of cards) {
    const product = card?.pricing?.cardmarket?.idProduct;
    if (!product) continue;
    byProduct.set(product, [...(byProduct.get(product) ?? []), card]);
  }
  const ids = [...byProduct.values()].flatMap((shared) => shared.sort(byNumber).slice(1).map((card) => card.id));
  if (ids.length > 0) {
    unreliable[setId] = ids.sort();
    total += ids.length;
    console.log(setId.padEnd(13), ids.length);
  }
}

const source = `// Generated by scripts/build-unreliable-prices.mjs. Do not edit by hand.
// Cards whose Cardmarket price on TCGdex belongs to another card of the same set, by TCGdex set id.

export const UNRELIABLE_PRICES: Record<string, readonly string[]> = ${JSON.stringify(unreliable, null, 2)};
`;
writeFileSync(new URL('../src/features/catalog/unreliable-prices.ts', import.meta.url), source);
console.log(`${total} cards without a reliable price`);
